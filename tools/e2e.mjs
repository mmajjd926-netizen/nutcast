// Headless smoke test: demo feed, top up on testnut, boost, screenshot. Usage: node tools/e2e.mjs <url>
import { chromium } from 'playwright';
const url = process.argv[2] ?? 'http://127.0.0.1:4173/';
const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: 1280, height: 1000 } });
const logs = [];
p.on('console', (m) => logs.push(m.type() + ': ' + m.text()));
p.on('pageerror', (e) => logs.push('pageerror: ' + e.message));
await p.goto(url);
await p.click('#demoBtn');
await p.waitForSelector('#episodes li', { timeout: 15000 });
console.log('show:', await p.textContent('#showTitle'));
console.log('split:', (await p.$$eval('#split li', (l) => l.map((x) => x.innerText.replace(/\s+/g, ' ')))).join(' | '));
await p.click('#walletBtn');
await p.fill('#topupAmt', '300');
await p.click('#topupBtn');
await p.waitForFunction(() => document.getElementById('balance').textContent !== '0', null, { timeout: 30000 });
console.log('balance after top-up:', await p.textContent('#balance'));
await p.click('button[value=close]');
await p.fill('#boostAmt', '50');
await p.fill('#boostMsg', 'Lovely reading!');
await p.click('#boostBtn');
await p.waitForSelector('#history li', { timeout: 30000 });
await p.waitForTimeout(3000);
console.log('history:', (await p.$$eval('#history li', (l) => l.map((x) => x.innerText.replace(/\s+/g, ' ')))).join(' | '));
console.log('balance after boost:', await p.textContent('#balance'));
// episode 2 pays ecash over NUT-18 (Nostr transport)
await p.click('#episodes li:nth-child(2) button');
await p.waitForTimeout(500);
console.log('split ep2:', (await p.$$eval('#split li', (l) => l.map((x) => x.innerText.replace(/\s+/g, ' ')))).join(' | '));
await p.fill('#boostAmt', '21');
await p.fill('#boostMsg', 'ecash boost test');
await p.click('#boostBtn');
await p.waitForFunction(() => document.querySelectorAll('#history li').length >= 3, null, { timeout: 30000 });
console.log('history:', (await p.$$eval('#history li', (l) => l.map((x) => x.innerText.replace(/\s+/g, ' ')))).join(' | '));
console.log('balance after ecash boost:', await p.textContent('#balance'));
await p.screenshot({ path: 'shots/demo.png', fullPage: true });
console.log(logs.filter((l) => !l.startsWith('debug')).slice(0, 15).join('\n'));
await b.close();
