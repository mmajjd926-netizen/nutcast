// Records the nutzap demo: top up on testnut, nutzap boost to the show, then stream to the show as nutzaps.
// Usage: node tools/demo-nutzap-video.mjs <url>; then tools/gif.sh shots/video-nz shots/nutzap-stream.gif
import { chromium } from 'playwright';
const url = process.argv[2] ?? 'http://127.0.0.1:4173/';
const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const ctx = await b.newContext({ viewport: { width: 1100, height: 760 }, recordVideo: { dir: 'shots/video-nz', size: { width: 1100, height: 760 } } });
const p = await ctx.newPage();
const wait = (ms) => p.waitForTimeout(ms);
const type = async (sel, text) => { await p.fill(sel, ''); await p.type(sel, text, { delay: 60 }); };
await p.goto(url);
await wait(1000);
await p.click('#demoBtn');
await p.waitForSelector('#episodes li', { timeout: 15000 });
await p.waitForSelector('#nzRow:not(.hidden)', { timeout: 20000 });
await wait(800);
await p.click('#walletBtn');
await wait(500);
await type('#topupAmt', '200');
await p.click('#topupBtn');
await p.waitForFunction(() => document.getElementById('balance').textContent !== '0', null, { timeout: 30000 });
await wait(1000);
await p.click('button[value=close]');
await p.locator('#nzRow').scrollIntoViewIfNeeded();
await type('#boostAmt', '21');
await type('#boostMsg', 'Nutzap from Nutcast');
await wait(400);
await p.click('#nzBtn');
await p.waitForFunction(() => /Sent|relay/.test(document.getElementById('nzState').textContent), null, { timeout: 30000 });
await wait(2000);
await p.locator('#streamNzRow').scrollIntoViewIfNeeded();
await p.fill('#rate', '60');
await p.check('#streamOn');
await wait(400);
await p.check('#streamNz');
await wait(600);
await p.click('#episodes li:nth-child(1) button');
await p.locator('#streamNzRow').scrollIntoViewIfNeeded();
await p.waitForFunction(() => window.nutcast.streamer.history.filter((h) => h.ok).length >= 1, null, { timeout: 60000 });
await p.locator('#history').scrollIntoViewIfNeeded();
await wait(3000);
await p.evaluate(() => document.getElementById('audio').pause());
const v = p.video();
await ctx.close();
console.log('video:', await v.path());
await b.close();
